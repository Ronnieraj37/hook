// Copies deployed addresses (../deployments) and contract ABIs (../out) into lib/generated.
// Run after every deploy: npm run sync
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../../", import.meta.url);
const read = (p) => JSON.parse(readFileSync(new URL(p, root), "utf8"));

const core = read("deployments/sepolia-core.json");
const tokens = read("deployments/sepolia-tokens.json");
const pools = read("deployments/sepolia-pools.json");
const faucet = read("deployments/sepolia-faucet.json").faucet;
writeFileSync(
  new URL("../lib/generated/deployment.json", import.meta.url),
  JSON.stringify({ chainId: 11155111, core: { ...core, faucet }, tokens, pools }, null, 2),
);

const abi = (name) => read(`out/${name}.sol/${name}.json`).abi;
// The router has several overloads; keep only the single-pool exact-input swap.
const router = abi("IUniswapV4Router04").filter(
  (f) =>
    f.type === "function" &&
    f.name === "swapExactTokensForTokens" &&
    f.inputs.some((i) => i.name === "poolKey"),
);
const out = [
  `// Generated by scripts/sync.mjs. Do not edit.`,
  `export const conditionalOrdersAbi = ${JSON.stringify(abi("ConditionalOrders"))} as const;`,
  `export const ruleHookAbi = ${JSON.stringify(abi("RuleHook"))} as const;`,
  `export const testTokenAbi = ${JSON.stringify(abi("TestToken"))} as const;`,
  `export const routerAbi = ${JSON.stringify(router)} as const;`,
  `export const faucetAbi = ${JSON.stringify(abi("TestFaucet"))} as const;`,
].join("\n\n");
writeFileSync(new URL("../lib/generated/abis.ts", import.meta.url), out + "\n");
console.log("synced", Object.keys(pools).length, "pools,", Object.keys(tokens).length, "tokens");
